#!/usr/bin/env bash
#
# Install the Phoenix-RTOS Rust toolchain: a rustc sysroot with std for every
# Phoenix target, rust-src and rust-lld. Point RUST_TOOLCHAIN_DIR at it, and
# check it with check-phoenix-toolchain.sh.
#
#   ./build-phoenix-toolchain.sh [options]
#
#   --prefix DIR     install directory (default: <build-dir>/install)
#   --build-dir DIR  bootstrap build directory (default: build/phoenix-toolchain)
#   --stage N        compiler stage (default: 1; 2 rebuilds rustc with itself, twice the time)
#   --with-cargo     install cargo too
#   --allow-dirty    build uncommitted changes
#   -j N             bootstrap jobs
set -euo pipefail

RUST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

PHOENIX_TARGETS=(
	riscv64gc-unknown-phoenix
	i586-unknown-phoenix
	aarch64-unknown-phoenix
	armv7a-unknown-phoenix
	armv7r-unknown-phoenix
	armv8r-unknown-phoenix
	sparc-unknown-phoenix
)

BUILD_DIR="$RUST_DIR/build/phoenix-toolchain"
PREFIX=""
STAGE=1
WITH_CARGO=n
ALLOW_DIRTY=n
JOBS=()

die() {
	echo "build-phoenix-toolchain.sh: $*" >&2
	exit 1
}

log() {
	printf '\n=== %s\n' "$*"
}

while [ $# -gt 0 ]; do
	case "$1" in
		--prefix) PREFIX="${2:?--prefix needs a directory}"; shift ;;
		--build-dir) BUILD_DIR="${2:?--build-dir needs a directory}"; shift ;;
		--stage) STAGE="${2:?--stage needs a number}"; shift ;;
		--with-cargo) WITH_CARGO=y ;;
		--allow-dirty) ALLOW_DIRTY=y ;;
		-j) JOBS=(-j "${2:?-j needs a number}"); shift ;;
		-h|--help) sed -n '2,/^set -euo/{/^set -euo/d;s/^# \{0,1\}//;p}' "${BASH_SOURCE[0]}"; exit 0 ;;
		*) die "unknown option '$1' (see --help)" ;;
	esac
	shift
done

mkdir -p "$BUILD_DIR"
BUILD_DIR="$(cd "$BUILD_DIR" && pwd)"
PREFIX="${PREFIX:-$BUILD_DIR/install}"
mkdir -p "$PREFIX"
PREFIX="$(cd "$PREFIX" && pwd)"

### sources

BACKTRACE_DIR="$RUST_DIR/library/backtrace"
[ -e "$BACKTRACE_DIR/Cargo.toml" ] || git -C "$RUST_DIR" submodule update --init library/backtrace

if [ "$ALLOW_DIRTY" = n ]; then
	for repo in "$RUST_DIR" "$BACKTRACE_DIR"; do
		[ -z "$(git -C "$repo" status --porcelain --untracked-files=no)" ] ||
			die "$repo has uncommitted changes (commit them, or pass --allow-dirty)"
	done
fi

# rust-src copies library/ including ignored files
STRAY="$(git -C "$RUST_DIR" status --porcelain --ignored -- library | grep '^[?!]' || true)"
[ -z "$STRAY" ] || die "untracked or ignored files would end up in rust-src (git clean -dX library):
$STRAY"

### build

CONFIG="$BUILD_DIR/bootstrap.toml"
cat >"$CONFIG" <<EOF
# Generated by build-phoenix-toolchain.sh; edits are overwritten.
include = ["$RUST_DIR/bootstrap.phoenix.toml"]

build.docs = false
# so cargo runs on hosts with other OpenSSL/curl versions
build.cargo-native-static = true
install.prefix = "$PREFIX"
install.sysconfdir = "etc"
# install goes through dist tarballs
dist.compression-profile = "fast"
dist.compression-formats = ["gz"]
EOF

COMPONENTS=(compiler/rustc library/std rust-src)
[ "$WITH_CARGO" = y ] && COMPONENTS+=(cargo)

log "Installing stage $STAGE into $PREFIX"
(cd "$RUST_DIR" && ./x.py install --config "$CONFIG" --build-dir "$BUILD_DIR" --stage "$STAGE" "${JOBS[@]}" "${COMPONENTS[@]}")
# they hold this machine's absolute paths
rm -f "$PREFIX/lib/rustlib/install.log" "$PREFIX/lib/rustlib/uninstall.sh"

echo
echo "check it: ./check-phoenix-toolchain.sh --build-dir $BUILD_DIR --prefix $PREFIX --project <phoenix-rtos-project>"
echo "export RUST_TOOLCHAIN_DIR=$PREFIX"
